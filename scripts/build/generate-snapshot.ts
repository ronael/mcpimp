import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { CAPABILITIES_DIR, CAPABILITY_SNAPSHOT_FILE } from "../../src/core/paths";
import { FileSystemCapabilityRegistry } from "../../src/registry/filesystem";

export interface SnapshotResult {
  outFile: string;
  count: number;
}

/**
 * Generates the Cloudflare Worker snapshot from `catalog/capabilities/`.
 *
 * Every MCPIMP path is resolved from the single `root` (the MCPIMP root), so
 * reading the catalog and writing `generated/` always stay consistent even when
 * `MCPIMP_ROOT` differs from the process working directory.
 */
export async function generateSnapshot(root: string): Promise<SnapshotResult> {
  const outFile = resolve(root, CAPABILITY_SNAPSHOT_FILE);
  const registry = await FileSystemCapabilityRegistry.scan(join(root, CAPABILITIES_DIR));
  const capabilities = registry.listCapabilities().map((capability) => ({
    ...capability,
    rootPath: undefined,
  }));

  const source = `// Auto-generated by scripts/build/generate-snapshot.ts. Do not edit by hand.
import type { Capability } from "../src/registry/types";

export const CAPABILITY_SNAPSHOT = ${JSON.stringify(capabilities, null, 2)} satisfies Capability[];
`;

  await mkdir(dirname(outFile), { recursive: true });
  await writeFile(outFile, source, "utf-8");

  return { outFile, count: capabilities.length };
}

const isDirectRun = process.argv[1] !== undefined && import.meta.url === pathToFileURL(resolve(process.argv[1])).href;

if (isDirectRun) {
  const root = resolve(process.env.MCPIMP_ROOT || process.cwd());
  const { outFile, count } = await generateSnapshot(root);
  console.log(`Generated ${outFile} with ${count} capabilities.`);
}
